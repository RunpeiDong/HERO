function lensGeometry(positions) {
  const segments = 64, layers = 4, stride = segments + 1, indices = [];
  for (let i = 0; i < segments; i++) indices.push(0, i + 1, i + 2);
  for (let row = 0; row < layers - 1; row++) for (let i = 0; i < segments; i++) {
    const a = 1 + row * stride + i, b = a + 1, d = a + stride, c = d + 1;
    indices.push(a, d, b, b, d, c);
  }
  // A CAD edge's changing normal can shift a tip slightly across its neighbour.
  // Keep every lens triangle front-facing without moving the fitted vertices.
  for (let i = 0; i < indices.length; i += 3) {
    const [a, b, c] = indices.slice(i, i + 3).map(index => positions[index]);
    const facing = (b[1] - a[1]) * (c[2] - a[2]) - (b[2] - a[2]) * (c[1] - a[1]);
    if (facing < 0) [indices[i + 1], indices[i + 2]] = [indices[i + 2], indices[i + 1]];
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(positions.flat(), 3));
  geometry.setIndex(indices); geometry.computeVertexNormals();
  geometry.computeBoundingBox(); geometry.computeBoundingSphere();
  return geometry;
}

/** No lights, textures, timers or physics: every disposable resource lives under this group. */
export function createG1HeadLights() {
  const group = new THREE.Group();
  group.name = 'G1 cyan face LEDs';
  group.userData.kind = 'g1_head_lights';
  const core = new THREE.MeshBasicMaterial({color: '#a1f7ff', toneMapped: false,
    side: THREE.FrontSide, depthTest: true, depthWrite: true});
  const nearGlow = new THREE.MeshBasicMaterial({color: '#23d9ff', transparent: true, opacity: .20,
    side: THREE.FrontSide, blending: THREE.AdditiveBlending, toneMapped: false, depthTest: true, depthWrite: false});
  const outerGlow = new THREE.MeshBasicMaterial({color: '#16c9f5', transparent: true, opacity: .075,
    side: THREE.FrontSide, blending: THREE.AdditiveBlending, toneMapped: false, depthTest: true, depthWrite: false});
  function add(name, geometry, material, order) {
    const mesh = new THREE.Mesh(geometry, material);
    mesh.name = name; mesh.renderOrder = order;
    // Retain head/hat occlusion. FrontSide makes the filled lens invisible from behind.
    mesh.castShadow = false; mesh.receiveShadow = false;
    group.add(mesh);
  }
  const curve = new THREE.CatmullRomCurve3(VISOR_RIM.map(point => new THREE.Vector3(...point)), true, 'centripetal');
  for (const [suffix, radius, material, order] of [
    ['bright core', .00042, core, 0],
    ['inner glow', .00085, nearGlow, 1],
    ['soft halo', .00135, outerGlow, 2],
  ]) add(`Visor rim ${suffix}`, new THREE.TubeGeometry(curve, 512, radius, 8, true), material, order);
  add('Forehead oval bright core', lensGeometry(FOREHEAD_LENS.core), core, 0);
  add('Forehead oval inner glow', lensGeometry(FOREHEAD_LENS.near), nearGlow, 1);
  add('Forehead oval soft halo', lensGeometry(FOREHEAD_LENS.halo), outerGlow, 2);
  return group;
}
